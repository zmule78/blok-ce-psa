package com.example.data.model

import java.text.SimpleDateFormat
import java.util.Locale

enum class TransactionSourceType {
    PAYMENT,
    FINANCE_ENTRY
}

enum class TransactionDirection {
    INCOMING,
    OUTGOING
}

enum class TransactionTypeFilter(val label: String) {
    ALL("Semua"),
    INCOMING("Pemasukan"),
    EXPENSES("Pengeluaran"),
    PENDING("Pending"),
    PAID("Lunas")
}

enum class TransactionDateFilter(val label: String) {
    ALL("Semua Tanggal"),
    SELECTED_MONTH("Bulan Terpilih"),
    LAST_7_DAYS("7 Hari"),
    LAST_30_DAYS("30 Hari")
}

data class AdminTransactionItem(
    val id: String,
    val sourceType: TransactionSourceType,
    val direction: TransactionDirection,
    val residentId: String,
    val residentName: String,
    val house: String,
    val title: String,
    val category: String,
    val methodOrKind: String,
    val status: String,
    val amount: Long,
    val monthCode: String,
    val dateLabel: String,
    val timestampMillis: Long,
    val note: String
)

fun buildUnifiedAdminTransactions(
    payments: List<Payment>,
    financeEntries: List<FinanceEntry>,
    residents: List<Resident>
): List<AdminTransactionItem> {
    val residentMap = residents.associateBy { it.id }

    val paymentItems = payments
        .filter { !it.isAutoGeneratedBill && (it.status == "paid" || it.status == "pending") }
        .map { pay ->
            val owner = residentMap[pay.userId]
            val cat = if (pay.type.equals("hidmat", ignoreCase = true)) "Hidmat" else "Iuran"
            val ts = pay.createdAt?.toDate()?.time
                ?: pay.updatedAt?.toDate()?.time
                ?: parseIndonesianDateLabelMillis(pay.dateLabel)
            AdminTransactionItem(
                id = "pay_${pay.id}",
                sourceType = TransactionSourceType.PAYMENT,
                direction = TransactionDirection.INCOMING,
                residentId = pay.userId,
                residentName = owner?.name?.ifBlank { owner.email } ?: "Warga (${pay.userId.take(6)})",
                house = owner?.house ?: "-",
                title = "$cat • ${monthLabel(pay.month)}",
                category = cat,
                methodOrKind = pay.method.ifBlank { "Transfer DANA" },
                status = pay.status,
                amount = pay.amount,
                monthCode = pay.month,
                dateLabel = pay.dateLabel.ifBlank { monthLabel(pay.month) },
                timestampMillis = ts,
                note = pay.note
            )
        }

    val entryItems = financeEntries.map { entry ->
        val isOut = entry.kind == "keluar"
        val ts = entry.createdAt?.toDate()?.time
            ?: entry.updatedAt?.toDate()?.time
            ?: parseIndonesianDateLabelMillis(entry.dateLabel)
        val kindTag = when (entry.kind) {
            "keluar" -> "Kas Keluar"
            "kas_blok" -> "Kas Blok"
            else -> "Kas Masuk"
        }
        AdminTransactionItem(
            id = "fin_${entry.id}",
            sourceType = TransactionSourceType.FINANCE_ENTRY,
            direction = if (isOut) TransactionDirection.OUTGOING else TransactionDirection.INCOMING,
            residentId = entry.createdByUid,
            residentName = entry.createdByName.ifBlank { "Admin Utama" },
            house = "Kas Blok",
            title = entry.title,
            category = entry.category.ifBlank { "Umum" },
            methodOrKind = kindTag,
            status = if (isOut) "expense" else "recorded",
            amount = entry.amount,
            monthCode = entry.month,
            dateLabel = entry.dateLabel.ifBlank { monthLabel(entry.month) },
            timestampMillis = ts,
            note = entry.note
        )
    }

    return (paymentItems + entryItems).sortedWith(
        compareByDescending<AdminTransactionItem> { it.timestampMillis }
            .thenByDescending { it.monthCode }
            .thenBy { it.title }
    )
}

fun extractTransactionCategories(items: List<AdminTransactionItem>): List<String> {
    val distinct = items
        .map { it.category.trim() }
        .filter { it.isNotBlank() }
        .distinctBy { it.lowercase(Locale.ROOT) }
        .sorted()
    return listOf("Semua") + distinct
}

fun filterAdminTransactions(
    items: List<AdminTransactionItem>,
    query: String,
    typeFilter: TransactionTypeFilter,
    categoryFilter: String,
    dateFilter: TransactionDateFilter,
    selectedMonth: String,
    nowMillis: Long = System.currentTimeMillis()
): List<AdminTransactionItem> {
    val cleanQuery = query.trim().lowercase(Locale.ROOT)
    val cleanCategory = categoryFilter.trim()
    val sevenDaysMs = 7L * 24L * 60L * 60L * 1000L
    val thirtyDaysMs = 30L * 24L * 60L * 60L * 1000L

    return items.filter { item ->
        val matchesType = when (typeFilter) {
            TransactionTypeFilter.ALL -> true
            TransactionTypeFilter.INCOMING -> item.direction == TransactionDirection.INCOMING
            TransactionTypeFilter.EXPENSES -> item.direction == TransactionDirection.OUTGOING
            TransactionTypeFilter.PENDING -> item.status == "pending"
            TransactionTypeFilter.PAID -> item.status == "paid" || item.status == "recorded"
        }
        if (!matchesType) return@filter false

        val matchesCategory = cleanCategory.isBlank() ||
            cleanCategory.equals("Semua", ignoreCase = true) ||
            item.category.equals(cleanCategory, ignoreCase = true)
        if (!matchesCategory) return@filter false

        val matchesDate = when (dateFilter) {
            TransactionDateFilter.ALL -> true
            TransactionDateFilter.SELECTED_MONTH -> item.monthCode == selectedMonth
            TransactionDateFilter.LAST_7_DAYS -> {
                if (item.timestampMillis > 0L) {
                    (nowMillis - item.timestampMillis) in 0L..sevenDaysMs
                } else {
                    item.monthCode == selectedMonth
                }
            }
            TransactionDateFilter.LAST_30_DAYS -> {
                if (item.timestampMillis > 0L) {
                    (nowMillis - item.timestampMillis) in 0L..thirtyDaysMs
                } else {
                    item.monthCode == selectedMonth
                }
            }
        }
        if (!matchesDate) return@filter false

        if (cleanQuery.isBlank()) return@filter true
        val monthFull = monthLabel(item.monthCode).lowercase(Locale.ROOT)
        item.residentName.lowercase(Locale.ROOT).contains(cleanQuery) ||
            item.house.lowercase(Locale.ROOT).contains(cleanQuery) ||
            item.title.lowercase(Locale.ROOT).contains(cleanQuery) ||
            item.category.lowercase(Locale.ROOT).contains(cleanQuery) ||
            item.methodOrKind.lowercase(Locale.ROOT).contains(cleanQuery) ||
            item.dateLabel.lowercase(Locale.ROOT).contains(cleanQuery) ||
            item.monthCode.lowercase(Locale.ROOT).contains(cleanQuery) ||
            monthFull.contains(cleanQuery) ||
            item.note.lowercase(Locale.ROOT).contains(cleanQuery)
    }
}

private fun parseIndonesianDateLabelMillis(dateLabel: String): Long {
    val clean = dateLabel.trim()
    if (clean.isBlank()) return 0L
    val formats = listOf("dd MMM yyyy", "dd/MM/yyyy", "yyyy-MM-dd", "dd-MM-yyyy")
    for (pattern in formats) {
        try {
            val fmt = SimpleDateFormat(pattern, Locale("id", "ID")).apply { isLenient = false }
            val parsed = fmt.parse(clean)
            if (parsed != null) return parsed.time
        } catch (_: Exception) {
            // Try next format
        }
        try {
            val fmtUs = SimpleDateFormat(pattern, Locale.US).apply { isLenient = false }
            val parsed = fmtUs.parse(clean)
            if (parsed != null) return parsed.time
        } catch (_: Exception) {
            // Try next format
        }
    }
    return 0L
}
